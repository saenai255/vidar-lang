// ---- what Vidar generates (appendix G), from docs/snippets/lowering ----

const lowerOrder = ["closure", "closure_ref", "interface", "destroy", "clone", "error_handling", "do_block", "anon_struct", "macro", "goroutine"];
const lowering = lowerOrder.map((name) => {
  const file = path.join(root, "docs", "snippets", "lowering", `${name}.vidar`);
  const src = fs.readFileSync(file, "utf8").split("\n");
  const meta = (k) => (src.find((l) => l.startsWith(`// ${k}: `)) ?? "").slice(k.length + 5);
  const code = src.filter((l) => !/^\/\/ (title|about): /.test(l)).join("\n");
  // only transpiled, never run: goroutines (disabled for now, src/sched.ts) still document their lowering
  const r = spawnSync("node", [path.join(root, "dist", "cli.js"), "emit", file], { encoding: "utf8", env: { ...process.env, VIDAR_GOROUTINES: "1" } });
  if (r.status !== 0) throw new Error(`emit failed for ${name}: ${r.stderr}`);
  const raw = r.stdout.split("\n");
  const cut = raw.findIndex((l) => /^\/\/ ==== (vidar_runtime|vidar_sched)/.test(l));
  const odin = (cut < 0 ? raw : raw.slice(0, cut)).filter((l) => l.trim() && !/^\/\/ ==== .* ====$/.test(l) && !/^\/\/ (title|about): /.test(l));
  return `## ${meta("title")}\n\n${meta("about")}\n\nYou write:\n\n${fence(name === "goroutine" ? "vidar,no_run" : "vidar", code)}\nVidar generates:\n\n${fence("odin", odin.join("\n"))}`;
});
