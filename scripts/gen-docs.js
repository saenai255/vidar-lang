#!/usr/bin/env node
// Writes the generated pages of the book (docs/src) from the compiler's own sources, and the examples and
// notes in docs/reference-src. `--check` fails if a page is stale.
//
// Every entry (keyword, built-in, attribute, directive, macro, flag, sched or rc proc, compile error) must
// have a section in docs/reference-src with at least one example; a section for a name the compiler doesn't
// have is an error too. See docs/reference-src/README.md.
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");
const d = require("../dist/lsp/docs.js");
const { parseBlocks } = require("./docblocks");

const root = path.join(__dirname, "..");
const bookDir = path.join(root, "docs", "src");
const notesDir = path.join(root, "docs", "reference-src");
const NOTE = "<!-- Generated by scripts/gen-docs.js from the compiler's sources and docs/reference-src. Do not edit; run npm run docs:gen. -->";

const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const list_ = (dir) => (fs.existsSync(path.join(root, dir)) ? fs.readdirSync(path.join(root, dir)).sort() : []);
const fence = (lang, text) => "```" + lang + "\n" + text.replace(/\s+$/, "") + "\n```\n";
const esc = (s) => s.replace(/[<>{}]/g, (c) => ({ "<": "&lt;", ">": "&gt;", "{": "&#123;", "}": "&#125;" })[c]);
const commentAbove = (lines, i) => {
  const out = [];
  for (let j = i - 1; j >= 0 && /^\s*\/\/ ?/.test(lines[j]); j--) out.unshift(lines[j].replace(/^\s*\/\/ ?/, ""));
  return out;
};
const problems = [];

// ---- the hand-written half: docs/reference-src/<file>.md, one "## `name`" section per entry ----

/** Sections of a notes file, by name. A section's text is everything under its heading. */
const notes = (file) => {
  const p = path.join(notesDir, file);
  const sections = new Map();
  if (!fs.existsSync(p)) {
    problems.push(`missing docs/reference-src/${file}`);
    return { sections, used: new Set(), file };
  }
  const lines = fs.readFileSync(p, "utf8").split("\n");
  const code = new Set();
  for (const b of parseBlocks(lines.join("\n"))) for (let i = b.start; i <= b.end; i++) code.add(i);
  let name = null;
  let body = [];
  const flush = () => {
    if (name !== null) sections.set(name, body.join("\n").trim());
  };
  lines.forEach((line, i) => {
    const m = !code.has(i) && /^## (.*)$/.exec(line);
    if (m) {
      flush();
      name = m[1].replace(/`/g, "").trim();
      body = [];
    } else if (name !== null) body.push(line);
  });
  flush();
  return { sections, used: new Set(), file };
};

/** The section for `name`; it must hold an example. */
const example = (n, name, { needs = ["vidar"] } = {}) => {
  n.used.add(name);
  const text = n.sections.get(name);
  if (text === undefined) {
    problems.push(`docs/reference-src/${n.file}: no section for \`${name}\``);
    return "";
  }
  if (!parseBlocks(text).some((b) => needs.includes(b.lang))) problems.push(`docs/reference-src/${n.file}: \`${name}\` has no ${needs.join(" or ")} example`);
  return text;
};

const unused = (n) => {
  for (const name of n.sections.keys()) if (!n.used.has(name)) problems.push(`docs/reference-src/${n.file}: \`${name}\` is not something the compiler has`);
};

const entries = (table) => Object.entries(table).sort(([a], [b]) => a.localeCompare(b));
const docOf = (v) => (typeof v === "string" ? { text: v } : v);

/** One entry: heading, signature, the compiler's description, then the examples. */
const entry = (level, name, { sig, text }, more, display = name) =>
  `${"#".repeat(level)} \`${display}\`\n\n${sig ? fence("odin", sig) + "\n" : ""}${text ? text + "\n\n" : ""}${more ? more + "\n" : ""}`;

/** A table of every entry, linking to it: name and the first sentence of its description. */
const firstSentence = (s) => {
  const m = /^(.*?[.!?])(\s|$)/s.exec(s ?? "");
  return (m ? m[1] : s ?? "").replace(/\n/g, " ").replace(/\|/g, "\\|");
};
const anchor = (name) => name.toLowerCase().replace(/[^\p{L}\p{N}_\s-]/gu, "").replace(/\s/g, "-");
const index = (items) => "| Name | What it is |\n|---|---|\n" + items.map(([name, text, display = name]) => `| [\`${display}\`](#${anchor(display)}) | ${firstSentence(text)} |`).join("\n") + "\n";

const page = (title, intro, body) => `${NOTE}\n\n# ${title}\n\n${intro}\n\n${body.replace(/\n+$/, "")}\n`;

