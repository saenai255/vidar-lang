// ---- compile errors (appendix F), from tests/errors and their notes ----

const errorCategory = (name) => {
  const rules = [
    [/^anon_struct/, "Anonymous struct literals"],
    [/^(closure_|capture_)/, "Closures"],
    [/^(catch_|errdefer_|or_return_)/, "Error handling"],
    [/^(destroy_|clone_|move_|owned_|rc_)/, "Destructors"],
    [/^(memo_|no_alloc|no_table|specialize_|table_|hot_)/, "Optimization attributes"],
    [/^(nested_plain_proc|not_captured)/, "Closures"],
    [/^stmt_macro/, "Comptime and macros"],
    [/^(duplicate_global|parse_)/, "Declarations and parsing"],
    [/^(comptime_|macro_|compile_error)/, "Comptime and macros"],
    [/^do_/, "`do!` blocks"],
    [/^(iface_|impl_|bodiless_|pool_)/, "Interfaces"],
    [/^(collection_|missing_|package_|private_)/, "Packages and imports"],
  ];
  return (rules.find(([re]) => re.test(name)) ?? [null, "Other"])[1];
};
const errorCases = [];
for (const f of list_("tests/errors")) {
  if (!f.endsWith(".vidar")) continue;
  const lines = read(`tests/errors/${f}`).split("\n");
  errorCases.push({ name: f.replace(/\.vidar$/, ""), message: lines[0].replace(/^\/\/ error: /, ""), files: [{ file: null, text: lines.slice(1).join("\n") }] });
}
for (const dir of list_("tests/errors_pkg")) {
  const base = `tests/errors_pkg/${dir}`;
  const files = [];
  const walk = (rel) => {
    for (const f of list_(`${base}/${rel}`)) {
      const sub = path.join(rel, f);
      if (fs.statSync(path.join(root, base, sub)).isDirectory()) walk(sub);
      else if (/\.(vidar|toml)$/.test(f)) files.push(sub.split(path.sep).join("/"));
    }
  };
  walk("");
  const main = read(`${base}/main.vidar`).split("\n");
  errorCases.push({
    name: dir,
    pkg: true,
    message: main[0].replace(/^\/\/ error: /, ""),
    files: files.map((f) => ({ file: f, text: f === "main.vidar" ? main.slice(1).join("\n") : read(`${base}/${f}`) })),
  });
}
const errNotes = notes("errors.md");
