const goroutineError = (c) => c.files.some((f) => /"vidar:sched"/.test(f.text)) && c.name === "package_goroutines_disabled";
const errorsBody =
  errorsToc +
  categories
    .map(([cat, cases]) => {
      const items = cases.map((c) => {
        const title = c.name.replace(/_/g, " ");
        // The failing program is tested by scripts/test.js; here it is shown, not compiled again.
        const code = c.files.length === 1 && !c.files[0].file
          ? fence("vidar,ignore", c.files[0].text)
          : c.files.map((f) => `<span class="filename">Filename: ${f.file}</span>\n\n${fence(f.file.endsWith(".toml") ? "toml" : "vidar,ignore", f.text)}`).join("\n");
        const fix = goroutineError(c) ? errNotes.sections.get(c.name) ?? "" : example(errNotes, c.name);
        if (goroutineError(c)) errNotes.used.add(c.name);
        return `### ${title}\n\nThis program doesn't compile:\n\n${code}\nThe message contains:\n\n${fence("text,error-output", c.message)}\n${fix}\n`;
      });
      return `## ${cat}\n\n${items.join("\n")}`;
    })
    .join("\n");
