const BARE_PARENTS = new Set(["Call", "ValueDecl", "Assign", "Return", "CompoundLit", "FieldValue", "Paren"]);

/** Statement lists, where a statement may become several lines. */
function isList(n: Node): boolean {
  return n.k === "Case" || (n.k === "Block" && !n.inline && (n.start === 0 || n.toks[n.start].text === "{"));
}

function n0(b: Block): number {
  return -(b.toks[b.start]?.pos.line ?? 0);
}

/** Whitespace between tokens of generated code: kept to one line (line comments become block comments). */
function squash(pre: string): string {
  if (!pre.includes("\n")) return pre;
  const comments = pre.match(/\/\/[^\n]*|\/\*[\s\S]*?\*\//g) ?? [];
  const inline = comments.map((c) => (c.startsWith("//") ? `/*${c.slice(2)} */` : c.replace(/\s*\n\s*/g, " ")));
  return inline.length ? ` ${inline.join(" ")} ` : " ";
}

/** Turns the line markers into line breaks and returns the source line of each output line. */
function resolveLines(marked: string): EmittedFile {
  const lines = [1];
  let src = 1;
  let text = "";
  for (let i = 0; i < marked.length; i++) {
    const c = marked[i];
    if (c === "\n") {
      lines.push(++src);
      text += c;
    } else if (c === GEN_NL) {
      const end = marked.indexOf(GEN_NL_END, i);
      lines.push(Number(marked.slice(i + 1, end)));
      text += "\n";
      i = end;
    } else if (c === SKIP_LINE) src++;
    else text += c;
  }
  return { text, lines };
}

function relImport(fromDir: string, toDir: string): string {
  return posix.relative(fromDir || ".", toDir || ".") || ".";
}

/** Pads generated code to the line count of the code it replaces, so later line numbers still match. */
function keepLines(n: Node, text: string): string {
  let lines = 0;
  for (let i = n.start + 1; i < n.end; i++) lines += n.toks[i].pre.split("\n").length - 1;
  const have = text.split("\n").length - 1;
  return have < lines ? text + "\n".repeat(lines - have) : text;
}
